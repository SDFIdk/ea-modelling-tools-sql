<#
.SYNOPSIS
    Builds the EA Modelling Tools SQL artefacts.

.DESCRIPTION
    Generates 4 files:
        1. an MDG Technology File (mdg_eamt_sql.xml);
        2. a file containing the searches, following the same structure as in 
        searches exported from EA and as in C:\Users\<username>\AppData\Roaming\Sparx Systems\EA\Search Data\EA_Search.xml
        (ea_search.xml);
        3. a file containing the search views (ea_modelviews.xml), a simple copy of the search views file in the source code;
        4. an HTML file listing all the searches and their comments (index.html).
    
    Those files are generated by means of XSLT transformations, defined in the *.xsl files in the build folder.
    
    Requires the following environment variables:
    - JAVA_HOME: points to a JDK or JRE installation
    - SAXON_CP: points to the main Saxon JAR file

.PARAMETER MdgVersion
    The version number (format x.y.z) of the generated MDG file.

.EXAMPLE
    .\build.ps1 -MdgVersion x.y.z
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)]
    [ValidateNotNullOrEmpty()]
    [string]$MdgVersion
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# See https://stackoverflow.com/questions/57131654/using-utf-8-encoding-chcp-65001-in-command-prompt-windows-powershell-window/57134096#57134096
$OutputEncoding = [Console]::InputEncoding = [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding

if (-not $env:JAVA_HOME) {
    Throw "Environment variable JAVA_HOME is not set."
}
Write-Verbose "JAVA_HOME=$env:JAVA_HOME"
$JavaExe = Join-Path $env:JAVA_HOME "bin\java.exe"
if (-not (Test-Path -LiteralPath $JavaExe)) {
    Throw "java.exe not found at: '$JavaExe'"
}

if (-not $env:SAXON_CP) {
    Throw "Environment variable SAXON_CP is not set."
}
Write-Verbose "SAXON_CP=$env:SAXON_CP"
if (-not (Test-Path -LiteralPath $env:SAXON_CP)) {
    Throw "Saxon JAR not found at: '$env:SAXON_CP'"
}

$ProjectRoot = Split-Path -Parent $PSScriptRoot
$SrcFolder = Join-Path $ProjectRoot "src"
$TargetFolder = Join-Path $ProjectRoot "target"

$CombineMdgXsltPath = Join-Path $PSScriptRoot "combine_ea_searches_mdg.xsl"
$CombineImportExportXsltPath = Join-Path $PSScriptRoot "combine_ea_searches_import_export.xsl"
$DocumentationXsltPath = Join-Path $PSScriptRoot "create_mdg_documentation.xsl"

$MdgFileName = "mdg_eamt_sql.xml"
$SearchesFileName = "ea_search.xml"
$ViewsFileName = "ea_modelviews.xml"
$DocumentationFileName = "index.html"

$MdgFilePath = Join-Path $TargetFolder $MdgFileName
$SearchesFilePath = Join-Path $TargetFolder $SearchesFileName
$ViewsFilePath = Join-Path $TargetFolder $ViewsFileName
$DocumentationFilePath = Join-Path $TargetFolder $DocumentationFileName
$SourceViewsFilePath = Join-Path $SrcFolder "modelviews\modelviews.xml"

if (Test-Path $TargetFolder) {
    Remove-Item -Recurse $TargetFolder
    Write-Host "INFO Deleted folder $TargetFolder"
}
New-Item $TargetFolder -ItemType Directory
Write-Host "INFO Folder $TargetFolder created successfully"

Write-Host "INFO Building MDG"
& "$JavaExe" `
    -cp "$env:SAXON_CP" `
    net.sf.saxon.Transform `
    "-xsl:$CombineMdgXsltPath" `
    -it:"start-template" `
    "-o:$MdgFilePath" `
    "folderPath=$SrcFolder" `
    "version=$MdgVersion"

Write-Host "INFO Building (editable) searches"
& "$JavaExe" `
    -cp "$env:SAXON_CP" `
    net.sf.saxon.Transform `
    "-xsl:$CombineImportExportXsltPath" `
    -it:"start-template" `
    "-o:$SearchesFilePath" `
    "folderPath=$SrcFolder"

Write-Host "INFO Copying (editable) model views"
Copy-Item $SourceViewsFilePath -Destination $ViewsFilePath
(Get-Item $ViewsFilePath).LastWriteTime = (Get-Date)
(Get-Item $ViewsFilePath).CreationTime = (Get-Date)

Write-Host "INFO Building documentation"
& "$JavaExe" `
    -cp "$env:SAXON_CP" `
    net.sf.saxon.Transform `
    "-s:$MdgFilePath" `
    "-xsl:$DocumentationXsltPath" `
    -it:"start-template" `
    "-o:$DocumentationFilePath" `
    "folderPath=$SrcFolder" `
    "version=$MdgVersion" `
    "mdgFileName=$MdgFileName" `
    "searchesFileName=$SearchesFileName" `
    "viewsFileName=$ViewsFileName"

Write-Host "INFO Finished"